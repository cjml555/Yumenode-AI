path = sys.argv[1] if len(sys.argv) > 1 else "app/src/main/res/values-zh/strings.xml"
src = open(path, encoding="utf-8").read()

def esc(t: str) -> str:
    # En XML de recursos, ' y " se escapan cuando aparecen sueltos.
    return t.replace("&", "&amp;").replace("'", "\\'").replace('"', '\\"')

existing = set(re.findall(r'<string name="([^"]+)"', src))
add = {k: v for k, v in ZH.items() if k not in existing}
block = "\n".join(f'    <string name="{k}">{esc(v)}</string>' for k, v in add.items())
out = src.replace("</resources>", block + "\n</resources>")
open(path, "w", encoding="utf-8").write(out)
print(f"añadidas {len(add)} cadenas a {path}")
